def main():
    db = DatabaseManager()
    with db.get_connection() as conn:
        conn.execute("DELETE FROM conversations;")
        conn.execute("DELETE FROM audit_logs;")
        conn.execute("DELETE FROM sources;")
        conn.execute("DELETE FROM leads;")

    opp_service = OpportunityService(db=db)
    audit_service = AdversarialAuditService(db=db)

    print(f"Inserindo e auditando {len(VETS_DATA)} leads veterinários com CELULAR PESSOAL DO DONO comprovado...")

    # Insert in reverse order so item #1 (Del Care, MMFR, MS Ultrassonografia, etc.) has the latest updated_at and appears FIRST in Kanban!
    for idx, item in enumerate(reversed(VETS_DATA), start=1):
        disp_owner_phone = format_display_phone(item["owner_phone"])
        disp_clinic_phone = format_display_phone(item["clinic_phone"])

        source = Source(
            url=item["source_url"],
            title=f"Auditoria Forense de Titularidade Pessoal - {item['company']}",
            source_type=SourceType.E1,
            supports=["identity", "address", "no_website", "responsible", "phone_1to1"],
        )

        owner_contact = Contact(
            name=item["owner"],
            role=item["role"],
            phone=disp_owner_phone,
            type=ContactType.PERSONAL_PROFESSIONAL,
            confidence=ConfidenceLevel.HIGH,
            evidence_ids=[source.id],
        )

        clinic_contact = Contact(
            name=f"Recepção — {item['company']}",
            role="Atendimento / Recepção da Clínica (Fallback)",
            phone=disp_clinic_phone,
            type=ContactType.BUSINESS,
            confidence=ConfidenceLevel.HIGH,
            evidence_ids=[source.id],
        )

        business = Business(
            name=item["company"],
            category="Clínica Veterinária",
            city="Rio de Janeiro",
            neighborhood="Barra da Tijuca",
            address=item["address"],
            website="",
            website_status=WebsiteStatus.NO_WEBSITE_CONFIRMED,
        )

        dig = DigitalPresence(
            instagram=item["source_url"] if "instagram.com" in item["source_url"] else "",
            facebook=item["source_url"] if "facebook.com" in item["source_url"] else "",
            google_maps=f"https://www.google.com/maps/search/?api=1&query={item['company'].replace(' ', '+')}+Barra+da+Tijuca",
            other=[item["source_url"]],
        )

        opp = Opportunity(
            classification=OpportunityClass.STRONG,
            evidence=[
                item["evidence"],
                item["phone_provenance"],
                "Contato direto com o decisor/proprietário no celular pessoal (sem filtro de recepcionista).",
            ],
            hypothesis="Abordagem direta no celular pessoal do médico/sócio permite apresentar a proposta de estrutura digital sem bloqueio de secretária ou recepção.",
            uncertainties=[],
        )

        lead = Lead(
            business=business,
            contacts=[owner_contact, clinic_contact],
            digital_presence=dig,
            opportunity=opp,
            outreach=Outreach(recommended_contact_id=owner_contact.id),
            sources=[source],
            pipeline_status=PipelineStatus.QUALIFIED,
            metadata={"clinic_phone": disp_clinic_phone},
        )

        lead = db.save_lead(lead)
        lead, msg = opp_service.prepare_outreach(lead.id)
        lead = audit_service.attach_adversarial_audit(
            lead_id=lead.id,
            phone_provenance=item["phone_provenance"],
            decision_maker_analysis=item["decision_maker_analysis"],
            adversarial_challenge=item["adversarial_challenge"],
            adversarial_verdict=item["adversarial_verdict"],
            verified_sources=[item["source_url"]],
        )
        print(f"[{idx:02d}/{len(VETS_DATA)}] OK: {lead.business.name} | {item['owner']}")
        print(f"        1º Pessoal Doutor : {disp_owner_phone} | 2º Clínica Fallback : {disp_clinic_phone}")
        print(f"        Msg Direta Doutor : {msg}")

    review_service = ReviewService(db=db)
    html_path = review_service.export_html_report()
    print(f"\nRelatório HTML exportado para: {html_path}")

    summary = audit_service.audit_all_leads(only_active=True, require_audit_dossier=True)
    print(
        f"\nAUDITORIA CONTRADITÓRIA FINAL: "
        f"Total={summary['total_audited']} | Aprovados={summary['passed']} | "
        f"Falhas={summary['failed']} | Colisões={summary['phone_collisions_count']}"
    )
    if not summary["all_passed"]:
        for r in summary["results"]:
            if not r["passed"]:
                print(f"  [FALHA] {r['business_name']}: {r['errors']}")


if __name__ == "__main__":
    main()
